def edit_message(message_id: int, new_text: str) -> bool:
    """
    Пытается отредактировать сообщение.
    Сначала пробует editMessageCaption (для постов с фото),
    если не получается — editMessageText.
    """
    base_url = f"https://api.telegram.org/bot{TOKEN}"

    # 1. Пробуем как caption (большинство постов с картинками)
    resp = requests.post(
        f"{base_url}/editMessageCaption",
        data={
            "chat_id": CHAT_ID,
            "message_id": message_id,
            "caption": new_text,
        },
        timeout=30,
    )
    data = resp.json()

    if data.get("ok"):
        print(f"✅ {message_id}: caption обновлён")
        return True

    # Если ошибка не "message is not modified" и не "there is no caption", пробуем text
    description = data.get("description", "")
    if "message is not modified" in description.lower():
        print(f"ℹ️  {message_id}: текст уже такой же, пропускаем")
        return True

    # 2. Пробуем как обычный текст
    resp2 = requests.post(
        f"{base_url}/editMessageText",
        data={
            "chat_id": CHAT_ID,
            "message_id": message_id,
            "text": new_text,
        },
        timeout=30,
    )
    data2 = resp2.json()

    if data2.get("ok"):
        print(f"✅ {message_id}: text обновлён")
        return True

    print(f"❌ {message_id}: не удалось отредактировать")
    print(f"   Caption error: {data.get('description')}")
    print(f"   Text error:    {data2.get('description')}")
    return False


def main():
    print(f"Редактируем {len(CORRECTIONS)} постов в {CHAT_ID}...\n")

    success = 0
    for msg_id, text in sorted(CORRECTIONS.items()):
        ok = edit_message(msg_id, text)
        if ok:
            success += 1
        time.sleep(0.4)  # небольшая пауза, чтобы не упереться в лимиты

    print(f"\nГотово: {success}/{len(CORRECTIONS)} постов обновлено.")


if __name__ == "__main__":
    main()
