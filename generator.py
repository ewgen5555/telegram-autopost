def _two_skills():
    s1, s2 = random.sample(SKILLS, 2)
    return s1, s2


def generate_game():
    age = random.choice(AGES)
    skill1, skill2 = _two_skills()
    char = random.choice(list(CHARACTERS.values()))
    objs = random.sample(OBJECTS, 3)
    text = random.choice(GAME_TEMPLATES).format(
        n=random.randint(3, 6),
        place=random.choice(PLACES),
        obj1=objs[0],
        obj2=objs[1],
        obj3=objs[2],
        skill=f"{skill1}, {skill2}",
        age=age,
        time=random.choice(TIMES),
        color=random.choice(COLORS),
        name=char["name"],
        ended=char["ended"],
    )
    hashtags = make_hashtags("game", skill1, age)
    full_text = text + "\n\n" + hashtags
    return full_text, char["name"]


def generate_task():
    age = random.choice(AGES)
    skill1, skill2 = _two_skills()
    char = random.choice(list(CHARACTERS.values()))
    letter = random.choice(LETTERS)
    words = WORDS_BY_LETTER[letter]
    text = random.choice(TASK_TEMPLATES).format(
        letter=letter,
        word1=words[0],
        word2=words[1],
        word3=words[2],
        shape=random.choice(SHAPES),
        obj1=random.choice(OBJECTS),
        skill=f"{skill1}, {skill2}",
        age=age,
        time=random.choice(TIMES),
        name=char["name"],
        ended=char["ended"],
    )
    hashtags = make_hashtags("task", skill1, age)
    full_text = text + "\n\n" + hashtags
    return full_text, char["name"]


def generate_tip():
    text = random.choice(TIP_TEMPLATES)
    hashtags = make_hashtags("tip")
    return text + "\n\n" + hashtags, None


def generate_story():
    text = random.choice(STORY_TEMPLATES)
    hashtags = make_hashtags("story")
    return text + "\n\n" + hashtags, None


def generate_post():
    category = random.choices(
        ["game", "task", "tip", "story"],
        weights=[40, 30, 15, 15],
        k=1
    )[0]

    if category == "game":
        text, character = generate_game()
    elif category == "task":
        text, character = generate_task()
    elif category == "tip":
        text, character = generate_tip()
    else:
        text, character = generate_story()

    if character is None:
        character = random.choice(["Мира", "Тима"])

    image = get_image_for_character(
        character=character,
        category=category,
        text=text,
    )

    return {
        "text": text,
        "image": image,
        "category": category,
        "character": character,
    }


if __name__ == "__main__":
    post = generate_post()
    print(post["text"])
    print("\n---")
    print("Category:", post["category"])
    print("Character:", post.get("character"))
    print("Image:", post["image"])
