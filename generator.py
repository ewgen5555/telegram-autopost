# -----------------------------
# Генерация постов
# -----------------------------

def generate_game():
    return GAME_TEMPLATES[random.randint(0, len(GAME_TEMPLATES)-1)].format(
        n=random.randint(3, 6),
        place=random.choice(PLACES),
        obj1=random.choice(OBJECTS),
        obj2=random.choice(OBJECTS),
        obj3=random.choice(OBJECTS),
        skill=random.choice(SKILLS),
        age=random.choice(AGES),
        time=random.choice(TIMES),
    )

def generate_task():
    letter = random.choice(LETTERS)
    words = WORDS_BY_LETTER[letter]
    return TASK_TEMPLATES[random.randint(0, len(TASK_TEMPLATES)-1)].format(
        letter=letter,
        word1=words[0],
        word2=words[1],
        word3=words[2],
        shape=random.choice(SHAPES),
        obj1=random.choice(OBJECTS),
        skill=random.choice(SKILLS),
        age=random.choice(AGES),
        time=random.choice(TIMES),
    )

def generate_tip():
    return random.choice(TIP_TEMPLATES)

def generate_story():
    return random.choice(STORY_TEMPLATES)

# -----------------------------
# Главный генератор
# -----------------------------

def generate_post():
    category = random.choice(["game", "task", "tip", "story"])

    if category == "game":
        text = generate_game()
    elif category == "task":
        text = generate_task()
    elif category == "tip":
        text = generate_tip()
    else:
        text = generate_story()

    image = get_image_for_category(category)

    return {
        "text": text,
        "image": image
    }

if __name__ == "__main__":
    post = generate_post()
    print(post["text"])
    print("\n---")
    print("Image:", post["image"])
